#!/usr/bin/env python3
"""MCP server #1 - a read-only database server exposing tools, a resource and a prompt.

WHAT THIS FILE IS
  A small Model Context Protocol (MCP) server that lets an AI client look inside a SQLite
  database safely. It is the "database" half of the MCP examples; devtools_server.py is the
  "pure logic" half.

WHAT MCP IS
  MCP is an open protocol (JSON-RPC messages) that standardises how an AI application
  (the "client", e.g. Claude Code) discovers and uses capabilities offered by a separate
  program (the "server"). Write the server once and any MCP-aware client can use it.

THE THREE MCP PRIMITIVES (all three are demonstrated below)
  * tool     - an action the MODEL decides to invoke (here: run a query, list tables).
  * resource - read-only context the APP or USER attaches (here: the schema), addressed by
               a URI such as schema://main. The model does not "call" it; it is loaded in.
  * prompt   - a reusable, parameterised prompt template the USER picks (here: a recipe for
               investigating duplicate rows). It surfaces e.g. as a slash command in clients.

HOW A SESSION WORKS (what the SDK handles for you)
  1. initialize   - client and server handshake and agree on protocol version/capabilities.
  2. list_tools   - client asks what tools exist; the SDK builds each tool's JSON schema
                    from the Python type hints and the docstring (the docstring becomes the
                    description the model reads, so write it for the model).
  3. call_tool    - client sends a tool name and arguments; the server runs the function
                    and returns the text result. list_resources / list_prompts work alike.

STDIO TRANSPORT - AND WHY STDOUT MUST STAY CLEAN
  "stdio" means the client launches this file as a child process and the two talk by
  writing protocol messages to the server's stdin/stdout. Therefore stdout IS the protocol
  channel: a stray print() would inject garbage into the JSON stream and break the session.
  Any logging must go to stderr (see main()).

SDK VERSION NOTE
  This uses the v2 MCP Python SDK, where the server class is MCPServer. In v1 the same
  thing was called FastMCP (mcp.server.fastmcp). Imports from older tutorials will fail.

HOW TO RUN (from the repo root)
  Standalone (it will just wait for protocol messages on stdin; Ctrl+C to stop):
      python examples/mcp/db_server.py --db examples/mcp/sample.sqlite
  Normally you do not run it by hand: Claude Code starts it from the entry in .mcp.json,
  and client_demo.py / client_with_claude.py / tests/test_assets_and_mcp.py spawn it too.
  If the --db file does not exist it is generated by playbook.sampledb (synthetic data).

SAFETY
  All SQL goes through playbook.sqlguard (keyword allow-list + read-only connection + row
  cap). Tool arguments come from a model and are treated as untrusted input.

GOTCHAS
  * The default DB path is relative, so run from the repo root.
  * Errors are returned as text starting "ERROR:" rather than raised, so the model can read
    the reason and retry with a corrected query.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from mcp.server.mcpserver import MCPServer

from playbook import sampledb, sqlguard

# The server object. The name is what clients display; `instructions` is a hint that clients
# may add to the model's context describing how to use this server.
mcp = MCPServer("dev-db", instructions="Read-only access to the application database. SELECT only.")
# Module-level so the tool functions (which take no db argument) can see the path chosen by
# --db in main(). Tools read it at call time, so changing it before mcp.run() takes effect.
_DB_PATH = "examples/mcp/sample.sqlite"


def _conn():
    # A fresh read-only connection per call: no shared state, and even a validator bug could
    # not write because SQLite itself opens the file in mode=ro.
    return sqlguard.open_readonly(_DB_PATH)


@mcp.tool()
def list_tables() -> str:
    """List tables and columns in the database."""
    # The docstring above is sent to the model as the tool description.
    with _conn() as conn:
        return json.dumps(sqlguard.describe_schema(conn), indent=2)


@mcp.tool()
def query(sql: str) -> str:
    """Run a single read-only SELECT (max 100 rows) and return JSON rows."""
    try:
        with _conn() as conn:
            return json.dumps(sqlguard.run_select(conn, sql), default=str)
    # NOTE: UnsafeSQL is already an Exception subclass, so listing both is redundant (harmless).
    # We catch broadly on purpose: any failure becomes readable text for the model.
    except (sqlguard.UnsafeSQL, Exception) as exc:  # surface the reason so the model can correct itself
        return f"ERROR: {exc}"


@mcp.resource("schema://main")
def schema_resource() -> str:
    """The database schema as attachable context."""
    # Reuses the tool's output so the resource and the tool can never disagree. This relies on
    # @mcp.tool() returning the original function (not exercised by the tests).
    return list_tables()


@mcp.prompt()
def investigate_duplicates(table: str, key_column: str) -> str:
    """Recipe: find rows that violate 'one active row per key'."""
    # A prompt only RETURNS text for the client to send as a user message; it runs no query.
    # It deliberately steers the model to the read-only tools and forbids executing writes.
    return (f"Investigate duplicate active rows in `{table}` grouped by `{key_column}`. "
            "First call list_tables, then use query with a GROUP BY ... HAVING COUNT(*) > 1. "
            "Report the offending keys and the SELECT you used. Do not propose writes except as text.")


def main() -> None:
    global _DB_PATH  # intentional: tools read this module-level setting
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=_DB_PATH)
    args = parser.parse_args()
    _DB_PATH = args.db
    # First run convenience: create the synthetic demo DB so the server works out of the box.
    if not Path(_DB_PATH).exists():
        sampledb.build(_DB_PATH)
    print(f"dev-db serving {_DB_PATH}", file=sys.stderr)  # stderr only: stdout is the protocol channel
    mcp.run()  # blocks, serving the stdio transport until the client closes the pipe


if __name__ == "__main__":
    main()
